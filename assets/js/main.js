document.addEventListener("DOMContentLoaded", () => {
  const lazySections = document.querySelectorAll(".lazy-section");

  const observer = new IntersectionObserver((entries, obs) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {

        // Load About Section
        if (entry.target.id === "about") {
          entry.target.innerHTML =
            document.querySelector("#about-template").innerHTML;
        }

        // Load Services Section
        if (entry.target.id === "services") {
          entry.target.innerHTML =
            document.querySelector("#services-template").innerHTML;
        }

        // Load Steps Section
        if (entry.target.id === "steps") {
          entry.target.innerHTML =
            document.querySelector("#step-template").innerHTML;
        }

        // Load FAQ Section
        if (entry.target.id === "faq") {
          entry.target.innerHTML =
            document.querySelector("#faq-template").innerHTML;

          // Re-initialize FAQ toggle after loading
          initFaqToggle();
        }

        // Load Contact Section
        if (entry.target.id === "contact") {
          entry.target.innerHTML =
            document.querySelector("#contact-template").innerHTML;
        }

        // Load Footer Section
        if (entry.target.id === "footer") {
          entry.target.innerHTML =
            document.querySelector("#footer-template").innerHTML;
        }

        entry.target.classList.add("loaded");
        obs.unobserve(entry.target);
      }
    });
  }, {
    rootMargin: "150px 0px",
    threshold: 0.1
  });

  lazySections.forEach(section => observer.observe(section));
});

